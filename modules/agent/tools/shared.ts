import { z } from "zod"

import { ASSESSMENTS, getAssessment } from "@/modules/assessments"
import type { EvidenceGrade } from "@/modules/memory"
import { QUESTION_IDS } from "@/modules/questionnaire"

export const questionIdSchema = z.enum(QUESTION_IDS)

export const assessmentIdSchema = z.enum(
  ASSESSMENTS.map(({ id }) => id) as [string, ...string[]]
)

/** Explainable autonomy: every tool call states why it's being made. */
export const reasonSchema = z
  .string()
  .min(1)
  .max(160)
  .describe(
    "Why you are doing this, in under twelve plain words. Shown to the user."
  )

/**
 * Agent-written text can't contain numerals, so it can't state a figure that
 * didn't come from the analytics engine. Evidence text is generated by code.
 */
export const narrativeSchema = z
  .string()
  .min(1)
  .max(240)
  .refine((text) => !/\d/.test(text), {
    message:
      "Write this without numerals. Figures are shown from the analysis automatically.",
  })

/** Resolves a metric, with an error the model can correct itself from. */
export function requireMetric(assessmentId: string, metricId: string) {
  const assessment = getAssessment(assessmentId)
  const metric = assessment?.metrics.find(({ id }) => id === metricId)
  if (!assessment || !metric) {
    const valid = assessment?.metrics.map(({ id }) => id).join(", ")
    throw new Error(
      `Unknown metric "${metricId}" for "${assessmentId}". Valid metrics: ${valid}.`
    )
  }
  return metric
}

export function requireField<T>(value: T | undefined, name: string): T {
  if (value === undefined) throw new Error(`"${name}" is required here.`)
  return value
}

/**
 * States a result's meaning, so its polarity can't be misread, and so a faint
 * or empty result can't be repeated as though it were a finding.
 */
export function describeEffect(
  assessmentId: string,
  metricId: string,
  analysis: {
    direction: "positive" | "negative" | "none"
    grade: EvidenceGrade
  }
) {
  const { direction, grade } = analysis
  if (grade === "insufficient") return "Not enough data to say anything yet."
  if (grade === "contradictory") {
    return "The pattern reversed over time, so no direction can be trusted."
  }
  if (direction === "none") return "No meaningful relationship in this data."
  const metric = requireMetric(assessmentId, metricId)
  const better = (direction === "positive") === metric.higherIsBetter
  const statement = `when this answer is higher, ${metric.label.toLowerCase()} tends to be ${
    direction === "positive" ? "higher" : "lower"
  }, which is ${better ? "better" : "worse"} performance.`
  return grade === "weak"
    ? `A faint pattern that could easily be chance: ${statement}`
    : statement[0]!.toUpperCase() + statement.slice(1)
}
